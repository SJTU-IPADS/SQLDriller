CREATE TABLE `Player`
(
    `id`                 INT PRIMARY KEY AUTO_INCREMENT,
    `player_api_id`      INT UNIQUE,
    `player_name`        TEXT,
    `player_fifa_api_id` INT UNIQUE,
    `birthday`           TEXT,
    `height`             INT,
    `weight`             INT
);
CREATE TABLE `League`
(
    `id`         INT PRIMARY KEY AUTO_INCREMENT,
