CREATE TABLE awards_players
(
    playerID TEXT NOT NULL,
    award    TEXT NOT NULL,
    year     INT  NOT NULL,
    lgID     TEXT NULL,
    note     TEXT NULL,
    pos      TEXT NULL,
    PRIMARY KEY (playerID, year, award),
    FOREIGN KEY (playerID) REFERENCES players (playerID)
);
CREATE TABLE coaches
(
    coachID     TEXT NOT NULL,
    year        INT  NOT NULL,
    tmID        TEXT NOT NULL,
    lgID        TEXT NULL,
    stint       INT  NOT NULL,
    won         INT  NULL,
    lost        INT  NULL,
    post_wins   INT  NULL,
    post_losses INT  NULL,
    PRIMARY KEY (coachID, year, tmID, stint),
    FOREIGN KEY (tmID, year) REFERENCES teams (tmID, year)
);
CREATE TABLE draft
(
    id             INT DEFAULT 0 NOT NULL PRIMARY KEY,
    draftYear      INT           NULL,
    draftRound     INT           NULL,
    draftSelection INT           NULL,
    draftOverall   INT           NULL,
    tmID           TEXT          NULL,
    firstName      TEXT          NULL,
    lastName       TEXT          NULL,
    suffixName     TEXT          NULL,
    playerID       TEXT          NULL,
    draftFrom      TEXT          NULL,
    lgID           TEXT          NULL,
    FOREIGN KEY (tmID, draftYear) REFERENCES teams (tmID, year)
);
CREATE TABLE player_allstar
(
    playerID        TEXT NOT NULL,
    last_name       TEXT NULL,
    first_name      TEXT NULL,
    season_id       INT  NOT NULL,
    conference      TEXT NULL,
    league_id       TEXT NULL,
    games_played    INT  NULL,
    minutes         INT  NULL,
    points          INT  NULL,
    o_rebounds      INT  NULL,
    d_rebounds      INT  NULL,
    rebounds        INT  NULL,
    assists         INT  NULL,
    steals          INT  NULL,
    blocks          INT  NULL,
    turnovers       INT  NULL,
    personal_fouls  INT  NULL,
    fg_attempted    INT  NULL,
    fg_made         INT  NULL,
    ft_attempted    INT  NULL,
    ft_made         INT  NULL,
    three_attempted INT  NULL,
    three_made      INT  NULL,
    PRIMARY KEY (playerID, season_id),
    FOREIGN KEY (playerID) REFERENCES players (playerID)
);
CREATE TABLE players
(
    playerID      TEXT  NOT NULL PRIMARY KEY,
    useFirst      TEXT  NULL,
    firstName     TEXT  NULL,
    middleName    TEXT  NULL,
    lastName      TEXT  NULL,
    nameGiven     TEXT  NULL,
    fullGivenName TEXT  NULL,
    nameSuffix    TEXT  NULL,
    nameNick      TEXT  NULL,
    pos           TEXT  NULL,
    firstseason   INT   NULL,
    lastseason    INT   NULL,
    height        FLOAT NULL,
    weight        INT   NULL,
    college       TEXT  NULL,
    collegeOther  TEXT  NULL,
    birthDate     DATE  NULL,
    birthCity     TEXT  NULL,
    birthState    TEXT  NULL,
    birthCountry  TEXT  NULL,
    highSchool    TEXT  NULL,
    hsCity        TEXT  NULL,
    hsState       TEXT  NULL,
    hsCountry     TEXT  NULL,
    deathDate     DATE  NULL,
    race          TEXT  NULL
