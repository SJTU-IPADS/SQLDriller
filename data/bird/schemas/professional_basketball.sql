create table teams
(
    year     INTEGER not null,
    lgID     TEXT,
    tmID     TEXT    not null,
    franchID TEXT,
    confID   TEXT,
    divID    TEXT,
    `rank`     INTEGER,
    confRank INTEGER,
    playoff  TEXT,
    name     TEXT,
    o_fgm    INTEGER,
    o_ftm    INTEGER,
    o_pts    INTEGER,
    d_pts    INTEGER,
    homeWon  INTEGER,
    homeLost INTEGER,
    awayWon  INTEGER,
    awayLost INTEGER,
    won      INTEGER,
    lost     INTEGER,
    games    INTEGER,
    arena    TEXT,
    primary key (year, tmID)
);
CREATE TABLE `awards_coaches`
(
    id      INT PRIMARY KEY AUTO_INCREMENT,
    year    INT,
    coachID TEXT,
    award   TEXT,
    lgID    TEXT,
    note    TEXT,
    FOREIGN KEY (coachID, year) REFERENCES coaches (coachID, year)
);
