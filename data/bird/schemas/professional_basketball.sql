CREATE TABLE `series_post`
(
    id         INT PRIMARY KEY AUTO_INCREMENT,
    year       INT,
    round      TEXT,
    series     TEXT,
    tmIDWinner TEXT,
    lgIDWinner TEXT,
    tmIDLoser  TEXT,
    lgIDLoser  TEXT,
    W          INT,
    L          INT,
    FOREIGN KEY (tmIDWinner, year) REFERENCES teams (tmID, year),
