CREATE TABLE institution_grads
(
    unitid        INT,
    year          INT,
    gender        TEXT,
    race          TEXT,
    cohort        TEXT,
    grad_cohort   TEXT,
    grad_100      TEXT,
    grad_150      TEXT,
    grad_100_rate TEXT,
    grad_150_rate TEXT,
    FOREIGN KEY (unitid) REFERENCES institution_details (unitid)
);
CREATE TABLE state_sector_grads
(
    stateid        INT,
    state          TEXT,
    state_abbr     TEXT,
    control        TEXT,
    level          TEXT,
    year           INT,
    gender         TEXT,
    race           TEXT,
    cohort         TEXT,
    grad_cohort    TEXT,
    grad_100       TEXT,
    grad_150       TEXT,
    grad_100_rate  TEXT,
    grad_150_rate  TEXT,
    grad_cohort_ct INT,
    FOREIGN KEY (state) REFERENCES institution_details (state),
    FOREIGN KEY (stateid) REFERENCES state_sector_details (stateid)
);
CREATE TABLE `state_sector_details`
(
    stateid                INT,
    state                  TEXT REFERENCES institution_details (state),
    state_post             TEXT,
    level                  TEXT,
    control                TEXT,
    schools_count          INT,
    counted_pct            TEXT,
    awards_per_state_value TEXT,
    awards_per_natl_value  FLOAT,
    exp_award_state_value  TEXT,
    exp_award_natl_value   INT,
    state_appr_value       TEXT,
    state_appr_rank        TEXT,
    grad_rate_rank         TEXT,
    awards_per_rank        TEXT,
    PRIMARY KEY (stateid, level, control)
);
