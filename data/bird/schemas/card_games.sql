CREATE TABLE `cards`
(
    id                      INT           NOT NULL PRIMARY KEY AUTO_INCREMENT,
    artist                  TEXT,
    asciiName               TEXT,
    availability            TEXT,
    borderColor             TEXT,
    cardKingdomFoilId       TEXT,
    cardKingdomId           TEXT,
    colorIdentity           TEXT,
    colorIndicator          TEXT,
    colors                  TEXT,
    convertedManaCost       FLOAT,
    duelDeck                TEXT,
    edhrecRank              INT,
    faceConvertedManaCost   FLOAT,
    faceName                TEXT,
    flavorName              TEXT,
    flavorText              TEXT,
    frameEffects            TEXT,
    frameVersion            TEXT,
    hand                    TEXT,
    hasAlternativeDeckLimit INT DEFAULT 0 NOT NULL,
    hasContentWarning       INT DEFAULT 0 NOT NULL,
    hasFoil                 INT DEFAULT 0 NOT NULL,
    hasNonFoil              INT DEFAULT 0 NOT NULL,
    isAlternative           INT DEFAULT 0 NOT NULL,
    isFullArt               INT DEFAULT 0 NOT NULL,
    isOnlineOnly            INT DEFAULT 0 NOT NULL,
    isOversized             INT DEFAULT 0 NOT NULL,
    isPromo                 INT DEFAULT 0 NOT NULL,
    isReprint               INT DEFAULT 0 NOT NULL,
    isReserved              INT DEFAULT 0 NOT NULL,
    isStarter               INT DEFAULT 0 NOT NULL,
    isStorySpotlight        INT DEFAULT 0 NOT NULL,
    isTextless              INT DEFAULT 0 NOT NULL,
    isTimeshifted           INT DEFAULT 0 NOT NULL,
    keywords                TEXT,
    layout                  TEXT,
    leadershipSkills        TEXT,
    life                    TEXT,
    loyalty                 TEXT,
    manaCost                TEXT,
    mcmId                   TEXT,
    mcmMetaId               TEXT,
    mtgArenaId              TEXT,
    mtgjsonV4Id             TEXT,
    mtgoFoilId              TEXT,
    mtgoId                  TEXT,
    multiverseId            TEXT,
    name                    TEXT,
    number                  TEXT,
    originalReleaseDate     TEXT,
    originalText            TEXT,
    originalType            TEXT,
    otherFaceIds            TEXT,
    power                   TEXT,
    printings               TEXT,
    promoTypes              TEXT,
    purchaseUrls            TEXT,
    rarity                  TEXT,
    scryfallId              TEXT,
    scryfallIllustrationId  TEXT,
    scryfallOracleId        TEXT,
    setCode                 TEXT,
    side                    TEXT,
    subtypes                TEXT,
    supertypes              TEXT,
    tcgplayerProductId      TEXT,
    text                    TEXT,
    toughness               TEXT,
    type                    TEXT,
    types                   TEXT,
    uuid                    TEXT          NOT NULL UNIQUE,
    variations              TEXT,
    watermark               TEXT
);
CREATE TABLE `foreign_data`
(
    id           INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    flavorText   TEXT,
    language     TEXT,
    multiverseid INT,
    name         TEXT,
    text         TEXT,
    type         TEXT,
    uuid         TEXT REFERENCES cards (uuid)
);
CREATE TABLE `legalities`
(
    id     INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    format TEXT,
    status TEXT,
    uuid   TEXT REFERENCES cards (uuid)
);
CREATE TABLE `sets`
(
    id               INT           NOT NULL PRIMARY KEY AUTO_INCREMENT,
    baseSetSize      INT,
    block            TEXT,
    booster          TEXT,
    code             TEXT          NOT NULL UNIQUE,
    isFoilOnly       INT DEFAULT 0 NOT NULL,
    isForeignOnly    INT DEFAULT 0 NOT NULL,
    isNonFoilOnly    INT DEFAULT 0 NOT NULL,
    isOnlineOnly     INT DEFAULT 0 NOT NULL,
    isPartialPreview INT DEFAULT 0 NOT NULL,
    keyruneCode      TEXT,
    mcmId            INT,
    mcmIdExtras      INT,
    mcmName          TEXT,
    mtgoCode         TEXT,
    name             TEXT,
    parentCode       TEXT,
    releaseDate      DATE,
    tcgplayerGroupId INT,
    totalSetSize     INT,
    type             TEXT
);
CREATE TABLE `set_translations`
(
    id          INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    language    TEXT,
    setCode     TEXT REFERENCES sets (code),
    translation TEXT
);
CREATE TABLE `rulings`
(
    id   INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    date DATE,
    text TEXT,
    uuid TEXT REFERENCES cards (uuid)
);
