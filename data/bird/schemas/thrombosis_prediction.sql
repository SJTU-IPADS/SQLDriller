CREATE TABLE Examination
(
    ID                 INT   NULL,
    `Examination Date` DATE  NULL,
    `aCL IgG`          FLOAT NULL,
    `aCL IgM`          FLOAT NULL,
    ANA                INT   NULL,
    `ANA Pattern`      TEXT  NULL,
    `aCL IgA`          INT   NULL,
    Diagnosis          TEXT  NULL,
    KCT                TEXT  NULL,
    RVVT               TEXT  NULL,
    LAC                TEXT  NULL,
    Symptoms           TEXT  NULL,
    Thrombosis         INT   NULL,
    FOREIGN KEY (ID) REFERENCES Patient (ID)
);
CREATE TABLE Patient
(
    ID           INT DEFAULT 0 NOT NULL PRIMARY KEY,
    SEX          TEXT          NULL,
    Birthday     DATE          NULL,
    Description  DATE          NULL,
    `First Date` DATE          NULL,
    Admission    TEXT          NULL,
    Diagnosis    TEXT          NULL
);
